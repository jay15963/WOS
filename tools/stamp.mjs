// Build identity stamp (node tools/stamp.mjs). Writes src/version.js:
//   BUILD_ID  — 12 hex of SHA-1 over every file under src/ (except version.js) + index.html
//   ART_ID    — 12 hex of SHA-1 over the art module graph (relative import walk from src/art/sprites.js)
//   BUILD_DATE, BUILD_FILES (paths hashed into BUILD_ID: the localhost self-check refetches them)
// and the VERSION line of sw.js ('wos-' + BUILD_ID). Text is LF-normalised before hashing, so the ids do
// not depend on the checkout's line endings. `--check` only verifies (exit 1 when stale).
// The same functions are used by tools/check-sync.mjs (rule R11).

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, dirname, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const rel = (p) => relative(ROOT, p).split(sep).join('/');
const norm = (s) => s.replace(/\r\n?/g, '\n');
const read = (p) => norm(readFileSync(join(ROOT, p), 'utf8'));

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(rel(p));
  }
  return out;
}

// same recipe as the browser self-check in src/main.js (devVersionCheck)
export function hashFiles(paths) {
  const h = createHash('sha1');
  for (const p of [...paths].sort()) h.update(p + '\n' + read(p) + '\n');
  return h.digest('hex').slice(0, 12);
}

export function buildFiles() {
  return walk(join(ROOT, 'src')).filter((p) => p !== 'src/version.js' && /\.(js|css|mjs|json|html)$/.test(p)).concat(['index.html']).sort();
}

// relative ES imports reachable from the entry (art graph = what the atlas painter runs)
export function importGraph(entry) {
  const seen = new Set();
  const stack = [entry];
  while (stack.length) {
    const p = stack.pop();
    if (seen.has(p)) continue;
    seen.add(p);
    const src = read(p);
    for (const m of src.matchAll(/(?:import|export)\s[^'";]*?from\s*['"](\.{1,2}\/[^'"]+)['"]/g)) {
      stack.push(rel(resolve(join(ROOT, dirname(p)), m[1])));
    }
  }
  return [...seen].sort();
}

export function computeIds() {
  const files = buildFiles();
  return { BUILD_ID: hashFiles(files), ART_ID: hashFiles(importGraph('src/art/sprites.js')), files };
}

export function readStamp() {
  const p = join(ROOT, 'src/version.js');
  if (!existsSync(p)) return null;
  const s = readFileSync(p, 'utf8');
  const get = (k) => (s.match(new RegExp(`export const ${k} = '([^']*)'`)) || [])[1] || null;
  return { BUILD_ID: get('BUILD_ID'), ART_ID: get('ART_ID'), BUILD_DATE: get('BUILD_DATE') };
}

export function swVersion() {
  const s = readFileSync(join(ROOT, 'sw.js'), 'utf8');
  return (s.match(/const VERSION = '([^']*)'/) || [])[1] || null;
}

function stamp() {
  const { BUILD_ID, ART_ID, files } = computeIds();
  const old = readStamp();
  const now = new Date();
  const pad = (n) => String(n).padStart(2, '0');
  const date = old && old.BUILD_ID === BUILD_ID && old.BUILD_DATE ? old.BUILD_DATE
    : `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())} ${pad(now.getHours())}:${pad(now.getMinutes())}`;
  const out = `// GENERATED by tools/stamp.mjs — do not edit by hand. Run \`node tools/stamp.mjs\` after changing src/ or index.html.
// BUILD_ID: hash of every file under src/ (except this one) + index.html. ART_ID: hash of the art module graph.
export const BUILD_ID = '${BUILD_ID}';
export const ART_ID = '${ART_ID}';
export const BUILD_DATE = '${date}';
export const BUILD_FILES = ${JSON.stringify(files)};
`;
  const vp = join(ROOT, 'src/version.js');
  if (!existsSync(vp) || readFileSync(vp, 'utf8') !== out) writeFileSync(vp, out);
  const swp = join(ROOT, 'sw.js');
  const sw = readFileSync(swp, 'utf8');
  const sw2 = sw.replace(/const VERSION = '[^']*';/, `const VERSION = 'wos-${BUILD_ID}';`);
  if (sw2 !== sw) writeFileSync(swp, sw2);
  return { BUILD_ID, ART_ID, date, n: files.length };
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  if (process.argv.includes('--check')) {
    const cur = computeIds(), st = readStamp();
    const ok = st && st.BUILD_ID === cur.BUILD_ID && st.ART_ID === cur.ART_ID && swVersion() === 'wos-' + cur.BUILD_ID;
    console.log(ok ? `stamp ok (${cur.BUILD_ID} / art ${cur.ART_ID})` : `stamp STALE: run node tools/stamp.mjs (have ${st?.BUILD_ID}/${st?.ART_ID}, want ${cur.BUILD_ID}/${cur.ART_ID})`);
    process.exit(ok ? 0 : 1);
  }
  const r = stamp();
  console.log(`stamped BUILD_ID ${r.BUILD_ID} · ART_ID ${r.ART_ID} · ${r.date} (${r.n} files)`);
}
